// Builds .claude/workflows/ticket-batch-thorough.js and ticket-batch-fast.js from ticket-batch.js.
// Each workflow is a whole script (its meta, MODE and the shared body) instead of a wrapper that calls a nested
// workflow: agents of a nested workflow are grouped under one extra phase, and the declared phases stay empty.
// Run with: node .claude/workflow-src/build.mjs          (writes the workflows)
//           node .claude/workflow-src/build.mjs --check  (exits 1 when a workflow is out of date)
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = new URL('./ticket-batch.js', import.meta.url);
const outDir = new URL('../workflows/', import.meta.url);

const PLAN = "{ title: 'Plan', detail: 'Opus planner per chunk of tickets', model: 'opus' }";
const BUILD = "{ title: 'Build', detail: 'Haiku per ticket; Sonnet takes over when Haiku fails', model: 'haiku' }";

export const WORKFLOWS = {
  'ticket-batch-thorough': {
    description:
      'Ticket batch: Opus plan, Haiku build (Sonnet if Haiku fails), Sonnet review per ticket, Opus batch review, merge and e2e',
    whenToUse: 'A batch of approved tickets where each ticket deserves its own QA review before the lead merges',
    phases: [
      PLAN,
      BUILD,
      "{ title: 'Review', detail: 'Sonnet QA per ticket as soon as it is built', model: 'sonnet' }",
      "{ title: 'Batch review', detail: 'Opus lead re-checks, merges into develop and runs e2e', model: 'opus' }",
    ],
  },
  'ticket-batch-fast': {
    description:
      'Ticket batch: Opus plan, Haiku build (Sonnet if Haiku fails), Opus review per chunk of up to 6 tickets, merge and e2e',
    whenToUse: 'A batch of approved tickets when speed matters; no per-ticket Sonnet review, one Opus reviewer per 6 tickets',
    phases: [
      PLAN,
      BUILD,
      "{ title: 'Batch review', detail: 'Opus reviews each chunk, merges into develop and runs e2e', model: 'opus' }",
    ],
  },
};

export function render(name, body) {
  const w = WORKFLOWS[name];
  const mode = name.replace('ticket-batch-', '');
  return [
    '// Generated by .claude/workflow-src/build.mjs from ticket-batch.js; edit those files, not this one.',
    'export const meta = {',
    `  name: '${name}',`,
    `  description: '${w.description}',`,
    `  whenToUse: '${w.whenToUse}',`,
    '  phases: [',
    ...w.phases.map((p) => `    ${p},`),
    '  ],',
    '}',
    '',
    `const MODE = '${mode}'`,
    '',
    body.replace(/\r\n/g, '\n').replace(/^(\/\/[^\n]*\n)+\n/, ''),
  ].join('\n');
}

export function outputs() {
  const body = fs.readFileSync(src, 'utf8');
  return Object.keys(WORKFLOWS).map((name) => ({
    file: fileURLToPath(new URL(`${name}.js`, outDir)),
    text: render(name, body),
  }));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const { file, text } of outputs()) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current === text) continue;
    if (check) {
      console.error(`out of date: ${file}`);
      stale++;
    } else {
      fs.writeFileSync(file, text);
      console.log(`wrote ${file}`);
    }
  }
  process.exit(stale ? 1 : 0);
}
